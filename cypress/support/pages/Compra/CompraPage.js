    preencherCFOP(cfop = '1102') {
        // Aguarda a tela de importação carregar completamente
        // Pode estar em uma URL diferente ou modal
        cy.url().should('include', '/compra');
        cy.wait(2000);
        // Tenta encontrar o formulário de importação ou o campo CFOP diretamente
        cy.get('body').then(($body) => {
            if ($body.find('#form-importacao').length > 0) {
                cy.get('#form-importacao', { timeout: 20000 }).should('be.visible');
            }
        });
        cy.get(CompraLocators.naturezaSelect, { timeout: 20000 })
            .should('be.visible')
            .clear()
            .type(cfop);
        cy.wait(1500); // Aguarda o autocomplete carregar
        cy.get('.typeahead-display', { timeout: 10000 })
            .should('be.visible')
            .click();
        return this;
    }

    clicarConfirmarNatureza() {
        cy.get('#form-importacao > :nth-child(2) > [style="padding: 0; margin: 0"]', { timeout: 10000 })
            .should('be.visible')
            .click();
        return this;
    }

